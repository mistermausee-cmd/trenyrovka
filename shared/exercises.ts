export type VisualView = 'front' | 'side' | 'three-quarter';

/**
 * Кадр для простой собственной схемы. UI может нарисовать силуэт и инвентарь,
 * используя короткие опорные точки, не завися от внешней иллюстрации.
 */
export interface ExerciseVisualFrame {
  readonly view: VisualView;
  readonly caption: string;
  readonly landmarks: readonly string[];
  readonly props: readonly string[];
}

export interface ExerciseVisual {
  readonly start: ExerciseVisualFrame;
  readonly end: ExerciseVisualFrame;
}

export interface VideoDuration {
  readonly seconds: number;
  readonly label: string;
}

export interface ConfirmedYouTubeVideo {
  readonly kind: 'youtube';
  readonly confirmed: true;
  readonly id: string;
  readonly url: string;
  readonly title: string;
  readonly source: string;
  /** null означает, что длительность не была независимо подтверждена. */
  readonly duration: VideoDuration | null;
}

export interface ExternalExerciseGuide {
  readonly kind: 'external-guide';
  readonly confirmed: false;
  readonly id: null;
  readonly url: string;
  readonly title: string;
  readonly source: string;
  readonly duration: null;
}

export type ExerciseVideo = ConfirmedYouTubeVideo | ExternalExerciseGuide;

export interface Exercise {
  readonly id: ExerciseId;
  readonly title: string;
  readonly purpose: string;
  readonly muscles: readonly MuscleGroup[];
  readonly equipment: readonly Equipment[];
  readonly measurement: MeasurementKind;
  readonly setup: readonly string[];
  readonly steps: readonly string[];
  readonly cues: readonly string[];
  readonly mistakes: readonly string[];
  readonly regression: string;
  readonly progression: string;
  readonly safety: readonly string[];
  readonly video: ExerciseVideo;
  readonly visual: ExerciseVisual;
}

